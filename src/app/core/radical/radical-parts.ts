/**
 * CHIẾT TỰ — mỗi chữ Hán trong khu Kanji tách ra thành những bộ thủ nào.
 *
 * Mỗi dòng là `chữ:thành phần+thành phần+…`. Đây là phần viết tay duy nhất của
 * khu "Bộ thủ": từ bảng này `npm run generate:radicals` gom ngược lại thành "bộ
 * thủ X có mặt trong những chữ nào", còn âm Hán Việt, cấp độ và từ ví dụ của
 * từng chữ thì lấy thẳng từ dữ liệu khu Kanji (`kanji-words.ts`).
 *
 * Quy ước:
 *  - Chữ ĐỘC THỂ (bản thân nó là bộ thủ, hoặc không tách được thành bộ nào) viết
 *    thành phần là chính nó: `日:日`.
 *  - Tách theo BIẾN THỂ đang thực sự viết trong chữ (亻 chứ không phải 人, 氵 chứ
 *    không phải 水) — bảng bộ thủ đã khai biến thể nên gom vẫn về đúng bộ gốc.
 *  - Thành phần nào lại tách được nữa thì script tự khai triển tiếp: `時:日+寺`
 *    và `寺:土+寸` cho ra 時 = 日+土+寸, nên 時 gom được về cả bộ 寸.
 *  - Chữ 𠂤 (phần bên phải của 追 / 師, phần trong của 官) không có trên bàn phím
 *    thông thường; bảng này viết là 自 cho đúng hình dáng người học nhìn thấy.
 *  - 月 ở đây là hình chữ nhìn thấy trên mặt giấy. Trong 服, 育, 勝, 能… nó vốn là
 *    bộ 肉 (nhục nguyệt ⺼) viết gọn lại, nhưng người học gõ và nhìn đều thấy 月 —
 *    tách theo hình để bảng tra khớp với thứ mắt nhìn thấy.
 *  - 阝 là một hình nhưng hai bộ: đứng TRƯỚC là 阜 (こざとへん), đứng SAU là 邑
 *    (おおざと). Script xét vị trí trong dòng chiết tự để chia đúng bộ.
 *
 * Danh sách chữ phải PHỦ ĐỦ `kanji-levels.ts`; thiếu chữ nào thì script báo lỗi.
 */

